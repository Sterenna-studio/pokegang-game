import assert from 'node:assert/strict';
import fs from 'node:fs';
import { makeSaveProgressFixture } from './fixtures/save-progress.mjs';
import { compareSaves, summarizeSave, validateSave } from './save-compare-core.js';

const { state } = makeSaveProgressFixture();
const before = structuredClone(state), after = structuredClone(state);
const id = Object.keys(after.zones)[0];
after.zones[id].gymDefeated = false;
after.missions.daily.claimed = [];
after.mewtwoMission.step++;
after._savedAt = 12345;
const result = compareSaves(before, after);
assert.equal(result.count, 3);
assert.ok(result.rows.some(row => row.path === `zones.${id}.gymDefeated`));
assert.ok(result.rows.some(row => row.path === 'missions.daily.claimed.0'));
assert.equal(summarizeSave(before)['Arènes vaincues'], 34);
assert.equal(summarizeSave(after)['Arènes vaincues'], 33);
assert.deepEqual(compareSaves(before, structuredClone(before)), { count: 0, rows: [] });
before.settings.llmApiKey = 'PRIVATE-BEFORE'; after.settings.llmApiKey = 'PRIVATE-AFTER';
const all = compareSaves(before, after, { all: true });
assert.ok(all.rows.some(row => row.path === 'settings.llmApiKey' && row.before === '[masqué]'));
assert.ok(!JSON.stringify(all).includes('PRIVATE'));
assert.equal(compareSaves(before, after, { limit: 1 }).rows.length, 1);
assert.throws(() => validateSave([]));
assert.throws(() => validateSave({ unrelated: true }));
assert.equal(before.zones[id].gymDefeated, true, 'Comparison does not mutate inputs');
assert.equal(compareSaves({ stats: { value: 1 } , gang: {} }, { stats: { value: '1' }, gang: {} }).rows[0].after, '"1"');
const entries = JSON.parse(fs.readFileSync(new URL('./lab-public-files.json', import.meta.url)));
assert.ok(entries.includes('sprite-lab.html') && entries.includes('save-compare.html'));
assert.ok(!entries.some(name => /dev-seed|fixture|build-|check-|test-|config\.js/.test(name)));
for (const entry of entries) assert.ok(fs.existsSync(new URL(entry, import.meta.url)), entry);
console.log('PASS lab tools: lost gym/quest claims detected, sensitive values masked, bounded diffs, read-only data and explicit public whitelist');
